"""Purpose: gate defects while reporting every unordered Python door boundary.

Guarantees: the report and catalog call the same source analysis. Mixed,
recursive and undeclared open boundaries fail. Supplied parameter contracts
and their dependent doors stay unordered and remain visible
[tested: test_door_order_gate_refuses_each_boundary_defect,
test_declared_supplied_callable_is_unordered_by_contract,
test_composition_of_contract_open_door_is_unordered_by_dependency; commit=07976cf8b415390449863d803277b73102673b51].
The shipped verdict table metta/doors/_orders.py is a projection of this
analysis: --write regenerates it and a check refuses drift, so a boot reads
the table instead of analysing the tree [tested:
test_door_order_gate_refuses_a_stale_verdict_table,
test_verdict_table_round_trips_every_verdict; commit=38aa006aa9ecb1ce5366439fee69474623e37091].
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from collections.abc import Mapping
from dataclasses import asdict
from graphlib import TopologicalSorter
from pathlib import Path

SEAT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SEAT))

import doorgen  # noqa: E402 -- the checkout source precedes an installed seat

from metta.doors._order import Order, Verdict, analyse, source_text  # noqa: E402
from metta.doors._scan import core_paths  # noqa: E402

TABLE = SEAT / "metta/doors/_orders.py"
NOTICE = (
    "GENERATED by extensions/python/tools/doororder.py --write from\n"
    "extensions/python/metta/**/*.py and extensions/python/ext/metta-*/*.py: the\n"
    "door-order lane refuses drift. Edit the inputs and regenerate this file."
)


def derived(root: Path = doorgen.ROOT) -> Mapping[str, Order]:
    """Analyse every declared door body in the actual source tree."""
    rows = doorgen.all_rows(root)
    paths = {module: path for path, module in core_paths(root / "extensions/python/metta")}
    for row in rows:
        if row.body:
            paths.setdefault(row.body.module, doorgen.module_path(row.body.module, root))
    return analyse(rows, source_text(paths))


def report(root: Path = doorgen.ROOT, orders: Mapping[str, Order] | None = None) -> dict:
    """Return every boundary and aggregate count for the actual source tree."""
    orders = derived(root) if orders is None else orders
    counts = Counter("unordered" if value.number is None else str(value.number) for value in orders.values())
    permitted = {name for name, value in orders.items() if value.number is not None}
    candidates = {name: value.blocked_by for name, value in orders.items()
                  if value.number is None and not (value.mixed or value.cycles or value.defect_open)}
    for name in TopologicalSorter(candidates).static_order():
        if name in candidates and candidates[name] <= permitted:
            permitted.add(name)
    return {
        "analysis": "Possible calls from a context-insensitive source graph. Declared caller-implemented contracts stay open; mixed crossings, recursion and other unresolved dispatch fail the gate. Every open call retains its owning source site.",
        "counts": dict(sorted(counts.items())),
        "first_order": sum(value.number == 1 for value in orders.values()),
        "mixed": [name for name, value in orders.items() if value.mixed],
        "open_dependencies": [name for name, value in orders.items() if value.open],
        "defect_open_dependencies": [name for name, value in orders.items() if value.defect_open],
        "unordered_by_contract": [name for name, value in orders.items()
                                  if name in permitted and value.number is None and value.contracts],
        "unordered_by_dependency": [name for name, value in orders.items()
                                    if name in permitted and value.number is None and not value.contracts],
        "recursive": [name for name, value in orders.items() if value.cycles],
        "rows": {name: {**asdict(value),
                        "contracts": [asdict(call) for call in sorted(value.contracts,
                                      key=lambda call: (call.site, call.parameter, call.annotation))]}
                 for name, value in orders.items()},
    }


def render(verdicts: Mapping[str, Verdict]) -> str:
    """The verdict table as the Python module the running seat imports."""
    lines = [
        '"""Purpose: publish each shipped door\'s order verdict without analysing the tree at boot.',
        "",
        *NOTICE.splitlines(),
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from types import MappingProxyType",
        "",
        "from metta.doors._order import Verdict",
        "",
        "VERDICTS: Mapping[str, Verdict] = MappingProxyType({",
    ]
    for key in sorted(verdicts):
        verdict = verdicts[key]
        reasons = "".join(f", {name}=True" for name in ("mixed", "open", "recursive", "dependency")
                          if getattr(verdict, name))
        lines.append(f"    {key!r}: Verdict({verdict.number!r}{reasons}),")
    lines += ["})", ""]
    return "\n".join(lines)


def drift(orders: Mapping[str, Order], table: Path | None = None) -> str | None:
    """The finding when the shipped table is absent or differs from the analysis."""
    table = TABLE if table is None else table
    wanted = render({name: value.verdict for name, value in orders.items()})
    if not table.is_file():
        return f"door-order: missing verdict table {table}; run {Path(__file__).name} --write"
    if table.read_text(encoding="utf-8") != wanted:
        return f"door-order: stale verdict table {table}; run {Path(__file__).name} --write"
    return None


def main(argv: list[str] | None = None) -> int:
    """Print every source-derived boundary and fail on unresolved findings or drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--write", action="store_true", help="regenerate the shipped verdict table")
    arguments = parser.parse_args(argv)
    orders = derived()
    if arguments.write:
        TABLE.write_text(render({name: value.verdict for name, value in orders.items()}), encoding="utf-8")
    result = report(orders=orders)
    if arguments.json:
        print(json.dumps(result, default=sorted, sort_keys=True, indent=2))
    else:
        print("door-order GATE:", json.dumps({key: value for key, value in result.items() if key != "rows"}))
        for name, row in result["rows"].items():
            print(name, json.dumps(row, default=sorted, sort_keys=True))
    finding = drift(orders)
    if finding:
        print(finding)
    return int(bool(finding) or any(result[key] for key in ("mixed", "defect_open_dependencies", "recursive")))


if __name__ == "__main__":
    raise SystemExit(main())
