"""Purpose: generate the MeTTa-library reference as templates over `metta.library.rows`.

The page reads the `(@doc ...)` atoms the MeTTa libraries carry, the same
true-by-construction promise reference.py makes for the Python modules:
both languages' docs come from their own sources through one pipeline.
The coverage table is the burn-down surface, interrogate's role for the
MeTTa side: a library gains entries here by gaining @doc atoms.

The generator is in two halves and neither prints. `catalog()` is the QUERY,
and the query is `metta.library.rows`, the one a library card renders too, so
a card and this page cannot disagree about what a library declares
[source: extensions/python/metta/library/__init__.py:186, rows; commit=cd62330ceacc8f1254eed9791c3f6203b48a1c9e]. It answers three `Rows`
-- one coverage row per library, one row per documented head, one row per
head a library carries and never documents -- and no text at all. Everything
below `_PAGE` is TEMPLATE: the page's own words are template literals,
`{coverage:table}` renders the coverage rows as the Markdown table this file
used to assemble a cell at a time, and every heading, prose line and
parameter is a hole. A second page over the same rows is a second template
rather than a second generator.

Iteration stays in Python, where the language has it: a template holds one
level, so each row's section is rendered by its own call and the pieces are
joined, which is the composition `{parts:lines}` and a nested template do
inside one template.

Assumes:
  - the engine's own reader parses each MeTTa implementation through the
    declarations reader; forms are READ and never run, while a Prolog-only
    implementation contributes a zero-documentation row rather than being
    parsed as MeTTa
    [tested: test_a_prolog_only_library_is_part_of_the_reference;
    commit=1bfad3db85807fff774cad370ff8e57f7400ae99]
Guarantees:
  - the checked-in page equals what this produces, gated on every run
    [tested test_the_metta_library_page_is_up_to_date]
  - the page renders the rows a library card renders, so the two cannot
    disagree about a head, its type or where it was written
    [tested: test_rows_are_the_query_the_reference_page_renders; commit=8bd4574fbc38b847d624ae1c75d9da3e18e0af69]
  - a head published through a runnable registration form is counted and
    named among the undocumented, which is what left lib_memo reading as an
    empty library while nine of its heads were callable [tested:
    test_a_registered_head_is_counted_in_the_reference; commit=8bd4574fbc38b847d624ae1c75d9da3e18e0af69]
  - the library roster comes from the runtime's shared `.metta`/`.pl` source
    discovery, with one row when a library has both halves
    [tested: test_metta_and_prolog_halves_share_one_library_row;
    commit=1bfad3db85807fff774cad370ff8e57f7400ae99]
  - `@doc` parts render in the order the atom writes them, so a library that
    puts `@return` before `@desc` reads as it was written
    [tested: test_a_doc_atom_renders_its_parts_in_written_order; commit=adb831d29a48596d3068a3087115b216c18b5b38]
  - a typed `(@param (@type T) (@desc D))` renders its DESCRIPTION, with the
    type named before it when the type says something, so the shape every
    Python-side doc atom is built in reads as prose rather than as an atom
    [tested: test_a_typed_parameter_renders_its_description; commit=7229962705d199fb08796b3090ec5a8a3a0ae393]
Guarantees: every declared overload appears in its head's reference entry
[tested: test_library_document_keeps_every_declared_arity; commit=9b22993447a5ddba93643895e3025661ba9f693e].
Fails when:
  - a library publishes names through a form whose name list is computed
    rather than written: the engine reports nothing for such a form, so those
    names go uncounted.
Open Obligations:
  To Do: None
  Hacks: None
  Future Enhancements: None
"""

from __future__ import annotations

import pathlib
import sys

_REPO = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(_REPO / "extensions" / "python"))

from typing import Any  # noqa: E402

from metta import Expression, Symbol, render  # noqa: E402
from metta._spaces.results import Rows  # noqa: E402
from metta.library import roster, rows  # noqa: E402

_PAGE = _REPO / "website" / "reference" / "metta-libraries.md"

#: The whole page: prose, the coverage rows as a table, and the sections.
_TEMPLATE = """# The MeTTa libraries

`!(import! &self (library lib_x))` loads one. The entries below reproduce
each library's own `(@doc ...)` atoms, generated by
`extensions/python/tools/libdoc.py`, so they are true by construction; `help!` and
`get-doc` answer the same atoms live. The coverage table is the
burn-down surface: a library appears below it by gaining `@doc` atoms
beside its definitions.

{coverage:table}

{sections}"""

#: One library's heading, above its documented names.
_SECTION = """## {library}

"""

#: One `@doc` atom's heading: the name it documents and where it is written.
_ENTRY = """### `{name}`

*{where}*

"""

#: The declared type, when the library states one for that name.
_DECLARED = """```metta
(: {name} {type})
```

"""

#: `(@desc ...)`, and `(@return ...)`, each one paragraph of the entry.
_DESCRIPTION = """{text}

"""

_RETURNS = """Returns: {text}

"""

#: `(@params (...))`, numbered from one, one line each.
_PARAMETERS = """{parameters:lines}

"""

_PARAMETER = "{position}. {detail}"

#: The names a library declares and does not document: the burn-down list.
_GAPS = """Undocumented: {names}

"""

_COVERAGE_COLUMNS = ("library", "names", "documented")
_ENTRY_COLUMNS = ("library", "name", "where", "parts")
_GAP_COLUMNS = ("library", "name")


def _where(row) -> tuple[str, int]:
    """A documented head's own position, which is the page's reading order.

    The rows arrive in the order the library first MENTIONS each head, which
    for a registered head is the line of the form that registers it, so a
    library registering ten names in one form would order those ten by the
    list rather than by their documentation. A documentation page reads in the
    order its documentation was written.
    """
    at = row.documentation_origin or row.origin
    return ("", 0) if at is None else (at.file, at.line or 0)


def catalog(root: pathlib.Path) -> tuple[Rows, Rows, Rows]:
    """The library catalog as rows: coverage, documented entries, and gaps.

    The query half of this generator, `metta.library.rows` applied to every
    library the runtime's own discovery names. Coverage counts one row per
    library (the heads it declares, defines, documents or registers, and how
    many carry a `@doc`), entries one row per documented head carrying that
    head's `@doc` parts in the order they were written and every type the
    library declares for it, and gaps one row per head the library carries
    (a type, an equation or a registration) and never documents.
    """
    coverage: list[tuple[Any, ...]] = []
    entries: list[tuple[Any, ...]] = []
    gaps: list[tuple[Any, ...]] = []
    for name in roster(root):
        library = Symbol(name)
        declared = rows(name, root=root)
        documented = sorted(
            (row for row in declared if row.documentation is not None), key=_where
        )
        for row in documented:
            at = row.documentation_origin or row.origin
            where = f"{pathlib.Path(at.file).name}:{at.line}" if at is not None else row.name
            entries.append(
                (
                    library,
                    Symbol(row.name),
                    where,
                    (tuple(row.types), tuple(row.documentation.children[2:])),
                )
            )
        if documented:
            gaps += [
                (library, Symbol(row.name))
                for row in sorted(
                    (row for row in declared if row.carried and row.documentation is None),
                    key=lambda row: row.name,
                )
            ]
        coverage.append((library, len(declared), len(documented)))
    return (
        Rows(_COVERAGE_COLUMNS, coverage),
        Rows(_ENTRY_COLUMNS, entries),
        Rows(_GAP_COLUMNS, gaps),
    )


def _detail(parts) -> object:
    """One `@param` or `@return` body as the text a reader wants.

    Two shapes reach here. A hand-written library writes the description
    itself, `(@param "a readable path")`, and the typed builder every Python
    door shares writes `(@param (@type Number) (@desc "how wide"))`; both are
    the same claim and this page had rendered the second one's TYPE ATOM as
    the whole entry, which lost every description torch's own docstrings
    carry. A parameter the source says nothing about renders as the type it
    has, which is all that is left to say about it.
    """
    described = None
    named = None
    for part in parts:
        if isinstance(part, Expression) and len(part.children) > 1:
            head, value = part.children[0], part.children[1]
            if head == Symbol("@desc"):
                described = value
            elif head == Symbol("@type"):
                named = value
    if described is None and named is None:
        return parts[0]
    #The TYPE is what the declaration block above prints in full, so an entry
    #prints it only where the source described nothing and there is otherwise
    #nothing left to say about that position.
    empty = getattr(described, "value", str(described)) == ""
    return named if described is None or empty else described


def _entry(row) -> str:
    """One `@doc` atom as Markdown: its heading, then one block per part.

    The parts render in the order the atom writes them, and a part this page
    has no template for is skipped rather than guessed at.
    """
    types, parts = row.parts
    text = render(_ENTRY, name=row.name, where=row.where)
    for type_atom in types:
        text += render(_DECLARED, name=row.name, type=type_atom)
    for part in parts:
        if not (isinstance(part, Expression) and part.children):
            continue
        head, *rest = part.children
        if head == Symbol("@desc") and rest:
            text += render(_DESCRIPTION, text=rest[0])
        elif head == Symbol("@params") and rest and isinstance(rest[0], Expression):
            numbered = [
                render(
                    _PARAMETER,
                    position=position,
                    detail=_detail(parameter.children[1:])
                    if (
                        isinstance(parameter, Expression)
                        and len(parameter.children) > 1
                    )
                    else parameter,
                )
                for position, parameter in enumerate(rest[0].children, start=1)
            ]
            if numbered:
                text += render(_PARAMETERS, parameters=numbered)
        elif head == Symbol("@return") and rest:
            text += render(_RETURNS, text=_detail(rest))
    return text


def sections(entries: Rows, gaps: Rows) -> str:
    """Every documented library's section, in the catalog's own order."""
    by_library = entries.group_by("library")
    missing = gaps.group_by("library")
    text = ""
    for library, documented in by_library.items():
        text += render(_SECTION, library=library)
        text += "".join(_entry(row) for row in documented)
        absent = missing.get(library)
        if absent:
            text += render(
                _GAPS, names=", ".join(f"`{row.name}`" for row in absent)
            )
    return text


def page() -> str:
    """Render the complete checked-in library reference page."""
    coverage, entries, gaps = catalog(_REPO)
    return (
        render(_TEMPLATE, coverage=coverage, sections=sections(entries, gaps)).rstrip()
        + "\n"
    )


def main(argv: list[str]) -> int:
    """Check the page, or regenerate it when ``--write`` is requested."""
    wanted = page()
    current = _PAGE.read_text(encoding="utf-8") if _PAGE.exists() else ""
    if current == wanted:
        return 0
    if "--write" in argv:
        _PAGE.write_text(wanted, encoding="utf-8")
        print(f"rewrote {_PAGE.name}")
        return 0
    print(
        f"{_PAGE.name} no longer matches the libraries' @doc atoms: "
        f"run extensions/python/tools/libdoc.py --write"
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
