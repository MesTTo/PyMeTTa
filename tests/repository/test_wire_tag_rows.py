"""Purpose: the wire grammar has one authority, and every copy of it is held here.

The grammar used to live in four places at once: the shim's clauses, an
eight-tag JSON payload table in `metta._schemas`, a nine-tag decoder-order
tuple in `metta._projection`, and the twelve-tag block in
`tests/codec/corpus.json` that generates `CODEC.md`'s table. The first three
now read the engine's own `(wire-tag ...)` rows. The corpus stays hand-written
because it is the artifact a third party downloads to check a codec written in
a language this engine has never run in, and it has to say what a tag means
without an engine to ask; this file is what keeps it saying the same thing.

Guarantees:
  - the corpus's tag block is exactly the engine's term and frame tags, with
    the same class, payload class and sentence [tested:
    test_the_corpus_carries_the_engines_term_and_frame_tags; commit=WORKTREE]
  - the reply tag is a row and deliberately not in the kit, because it is one
    door's answer shape rather than part of the atom grammar
    [tested: test_the_reply_tag_is_a_row_and_not_a_codec_case; commit=WORKTREE]
  - the corpus's profiles name only declared tags [tested:
    test_every_profile_names_declared_tags; commit=WORKTREE]
  - the OpenAPI atom schema has one arm per term tag, carrying the row's own
    sentence [tested: test_the_atom_schema_is_one_arm_per_term_tag; commit=WORKTREE]
Open Obligations:
  To Do: None
  Hacks: None
  Future Enhancements: None.
"""

import json
from pathlib import Path

import pytest

from metta import MeTTa
from metta._schemas import atom_schema
from metta.vocabularies import WIRE_TAGS, WireClass

REPO = Path(__file__).resolve().parents[4]

#: Read at import, like its neighbours: the cases below parametrize over it and
#: parametrize runs at collection time.
CORPUS = json.loads((REPO / "tests" / "codec" / "corpus.json").read_text())

_THE_ROW_IS_THE_NAME = (
    "the wire grammar is the (wire-tag <tag> <class> <payload> <means>) rows "
    "in engine/spaces/catalog.pl; regenerate the document with "
    "`python extensions/python/tools/codecdoc.py --write` after editing the "
    "corpus to match a changed row"
)


@pytest.fixture(scope="module")
def rows():
    """Every (wire-tag ...) row, read from a running catalog."""
    with MeTTa().space("&wire_tag_rows_probe") as space:
        answered = space.runtime.must(
            # _-prefixed because janus converts every NAMED variable of the
            # query and a findall template's variables are still free when it
            # answers, which janus reports as not sufficiently instantiated.
            "findall([_Tag, _Class, _Payload, _Means], "
            "metta_catalog_row(['wire-tag', _Tag, _Class, _Payload, _Means]), "
            "Rows)"
        )["Rows"]
    return {tag: (kind, payload, means) for tag, kind, payload, means in answered}


def test_the_generated_table_is_the_engines_rows(rows):
    """`metta.vocabularies.WIRE_TAGS` is generated by `vocabgen`, and this is
    the live engine saying the generator read it right.
    """  # noqa: D205  -- the contract is one claim, not summary-and-body prose
    assert set(WIRE_TAGS) == set(rows)
    for tag, row in WIRE_TAGS.items():
        kind, payload, means = rows[tag]
        assert (row.kind.value, row.payload.value, row.means) == (kind, payload, means)


def test_the_corpus_carries_the_engines_term_and_frame_tags(rows):
    """The conformance kit's tag block, held to the rows in both directions."""
    grammar = {
        tag: entry for tag, entry in rows.items() if entry[0] in {"term", "frame"}
    }
    assert list(CORPUS["tags"]) == list(grammar), _THE_ROW_IS_THE_NAME
    for tag, (kind, payload, means) in grammar.items():
        entry = CORPUS["tags"][tag]
        assert entry["class"] == kind, f"{tag}: {_THE_ROW_IS_THE_NAME}"
        assert entry["payload"] == payload, f"{tag}: {_THE_ROW_IS_THE_NAME}"
        assert entry["means"] == means, f"{tag}: {_THE_ROW_IS_THE_NAME}"


def test_the_reply_tag_is_a_row_and_not_a_codec_case(rows):
    """`r` is `metta_py_cast`'s answer shape, so a codec written against the
    kit does not implement it and the class column is what says so.
    """  # noqa: D205  -- the contract is one claim, not summary-and-body prose
    assert rows["r"][0] == "reply"
    assert "r" not in CORPUS["tags"]
    assert WIRE_TAGS["r"].kind is WireClass.reply


def test_every_profile_names_declared_tags(rows):
    """A profile is a subset of the grammar, so a tag in one and in no row
    would ask an implementer for something nothing defines.
    """  # noqa: D205  -- the contract is one claim, not summary-and-body prose
    for name, profile in CORPUS["profiles"].items():
        for tag in profile["tags"]:
            assert rows[tag][0] == "term", f"{name} names {tag}, which is no term tag"
        for tag in profile.get("frames", ()):
            assert rows[tag][0] == "frame", f"{name} names {tag}, which is no frame tag"


def test_the_atom_schema_is_one_arm_per_term_tag(rows):
    """The OpenAPI document's `Atom` schema is built from the rows, so a tag
    added to the catalog reaches a served gateway with no Python edit.
    """  # noqa: D205  -- the contract is one claim, not summary-and-body prose
    schema = atom_schema()
    arms = {arm["prefixItems"][0]["const"]: arm for arm in schema["oneOf"]}
    assert set(arms) == {tag for tag, entry in rows.items() if entry[0] == "term"}
    for tag, arm in arms.items():
        assert arm["description"].startswith(rows[tag][2])
