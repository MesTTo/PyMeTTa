    """Dispatch on a key that misses the literal branch."""
    @m.define
    def casetest(x):
        # (= (casetest $x) (case $x ((4 42) ($otherpattern 44) ($otherother $45))))
        match x:
            case 4:
                return 42
            case _:
                return 44

